# Base decimal
decimal = int('23', 10) # el 10 es la base decimal
print(f"Decimal: {decimal}")

#Base binaria
binario = int('10111', 2) # el 2 es la base binaria
print(f"Binario: {binario}")

# Base octal
octal = int('27', 8) # el 8 es la base octal   
print(f"Octal: {octal}")

# Base hexadecimal
hexadecimal = int('1F', 16) # el 16 es la base hexadecimal 
print(f"Hexadecimal: {hexadecimal}")

# Base 5 sus valores van de 0 a 4
base5 = int('43', 5) # el 5 es la base 5
print(f"Base 5: {base5}")
