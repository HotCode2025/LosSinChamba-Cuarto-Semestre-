# Profundizando en el tipo float como constructor y comienzo de exponencial
a = 3.0
print(f"a: {a: .2f}")

# Constructor de tipo float -> puede recibir int y string
b = float(10)
b = float('10')
print(f"b: {b: .2f}")

# Notacion exponencial (valores positivos o negativos)
c = 3e5 # 3 * 10^5
print(f"c: {c}")
